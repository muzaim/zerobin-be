package main

import (
	"context"
	"fmt"
	"log"
	"net/http"
	"os"
	"os/signal"
	"syscall"
	"time"

	"cellar-backend/configs"
	_ "cellar-backend/docs" // Will be generated by Swag
	"cellar-backend/internal/middleware"
	"cellar-backend/internal/modules/audit"
	"cellar-backend/internal/modules/health"
	"cellar-backend/internal/modules/user"
	"cellar-backend/pkg/auth"
	"cellar-backend/pkg/database"
	"cellar-backend/pkg/logger"

	"github.com/gin-gonic/gin"
	swaggerFiles "github.com/swaggo/files"
	ginSwagger "github.com/swaggo/gin-swagger"
)

// @title Golang SaaS Starter Kit API
// @version 1.0
// @description Production-ready Golang SaaS backend starter template.
// @termsOfService http://swagger.io/terms/

// @contact.name API Support
// @contact.url http://www.swagger.io/support
// @contact.email support@swagger.io

// @license.name Apache 2.0
// @license.url http://www.apache.org/licenses/LICENSE-2.0.html

// @host localhost:8080
// @BasePath /api/v1
// @query.collection.format multi

// @securityDefinitions.apiKey BearerAuth
// @in header
// @name Authorization
// @description Type "Bearer " followed by your JWT token.
func main() {
	// 1. Load configuration
	cfg, err := configs.LoadConfig()
	if err != nil {
		log.Fatalf("Failed to initialize config: %v", err)
	}

	// 2. Initialize Zerolog
	logger.InitLogger(cfg.App.Env, cfg.App.LogLevel)

	// 3. Connect to Database
	db, err := database.InitDB(&cfg.DB, cfg.App.Env)
	if err != nil {
		logger.Fatal(err, "Failed to connect to database")
	}

	// 4. Auto Migrate GORM models if enabled
	if cfg.DB.AutoMigrate {
		logger.Info("Auto-migration enabled. Running migrations...")
		err = db.AutoMigrate(
			&audit.AuditTrail{},
			&user.User{},
		)
		if err != nil {
			logger.Fatal(err, "Auto-migration failed")
		}
		logger.Info("Auto-migration completed successfully")
	}

	// 5. Initialize JWT service
	jwtService := auth.NewJWTService(&cfg.JWT)

	// 6. Initialize Casbin RBAC
	enforcer, err := auth.NewCasbinEnforcer("configs/rbac_model.conf", "configs/rbac_policy.csv")
	if err != nil {
		logger.Fatal(err, "Failed to load Casbin RBAC policies")
	}

	// 7. Set Gin execution mode
	if cfg.App.Env == "production" {
		gin.SetMode(gin.ReleaseMode)
	}

	// 8. Initialize Gin Router
	r := gin.New()

	// 9. Attach global middlewares
	r.Use(middleware.RequestID())
	r.Use(middleware.Logging())
	r.Use(middleware.Recovery())
	r.Use(middleware.CORS(&cfg.CORS))

	// 10. Register Swagger Endpoint
	r.GET("/swagger/*any", ginSwagger.WrapHandler(swaggerFiles.Handler))

	// 11. API Version 1 Group
	v1 := r.Group("/api/v1")

	// 12. Register Module Services and Repositories
	auditRepo := audit.NewRepository(db)
	auditServ := audit.NewService(auditRepo)

	userRepo := user.NewRepository(db)
	userServ := user.NewService(userRepo, auditServ, jwtService)

	healthHandler := health.NewHandler()
	userHandler := user.NewHandler(userServ)

	health.RegisterRoutes(v1, healthHandler)
	user.RegisterRoutes(v1, userHandler, jwtService, enforcer)

	// 13. Start HTTP Server with Graceful Shutdown
	srv := &http.Server{
		Addr:    fmt.Sprintf(":%s", cfg.App.Port),
		Handler: r,
	}

	go func() {
		logger.Info("Starting HTTP server on port %s...", cfg.App.Port)
		if err := srv.ListenAndServe(); err != nil && err != http.ErrServerClosed {
			logger.Fatal(err, "HTTP server listening failure")
		}
	}()

	// Wait for interrupt signal to gracefully shutdown the server
	quit := make(chan os.Signal, 1)
	signal.Notify(quit, syscall.SIGINT, syscall.SIGTERM)
	<-quit
	logger.Info("Shutting down HTTP server...")

	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	if err := srv.Shutdown(ctx); err != nil {
		logger.Fatal(err, "Server forced to shutdown")
	}

	logger.Info("Server exited gracefully")
}
